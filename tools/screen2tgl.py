#!/usr/bin/env python3
"""
screen2tgl.py - convert a teletext graphics screen into a table for the
Acorn System 3 Teletext Graphics Library.

Reads teletext screen memory (40 bytes per row), as a hex listing or as the
raw bytes, and writes
an assembler include holding the picture in the library's own buffer
layout: for each of the 24 graphics rows, the 39 cells of columns 1-39,
then the 24 rows' graphics colours (1-7). A program copies the cells into
the off-screen buffer and sets each row's colour with TGL_COLOUR (see
demo/logo.asm), after which every library routine - TGL_FLIPH included -
works on the picture.

Usage:
    python3 tools/screen2tgl.py LISTING [-o OUT.asm] [--label NAME]
                                [--first-row N]

LISTING is either:
  - the raw screen bytes, as saved by a teletext editor: 40 bytes per row,
    optionally with a newline after each row (recognised automatically,
    as it contains control codes rather than hex text); or
  - a text file of hex bytes. Lines may start with an address ("E400:",
    "0400", "$E400 -") and may end with an ASCII column; only two-digit
    hex bytes after the address are used.
It should hold 24 or 25 rows; --first-row picks which screen row becomes
graphics row 0 (default 0), and 24 rows are taken from there.

How each row is converted:
  - Its graphics colour is the first graphics colour code ($91-$97, with
    or without bit 7) found in the row; rows without one are white.
  - Column 0 is not copied (the library keeps the colour code there).
  - In columns 1-39, control codes ($00-$1F, $80-$9F) become blank cells.
    That includes the separated-graphics code ($9A): the library draws
    contiguous graphics, so separated pictures appear solid.
  - Sixel cells ($20-$3F, $60-$7F, bit 7 ignored) are copied as they are.
    Codes $40-$5F would show as capital letters even in graphics mode
    ("blast-through"); the library can't hold those, so they become blank,
    with a warning.
"""
import argparse, re, sys

COLS, ROWS = 40, 24

def read_screen(path):
    """Raw screen bytes or a hex listing, whichever the file is."""
    raw = open(path, 'rb').read()
    looks_like_text = all(b in b'\t\r\n' or 0x20 <= b < 0x7F for b in raw)
    if looks_like_text:
        data = read_listing(path)
        if len(data) >= ROWS * COLS:
            return data
    # raw bytes: drop a newline (or CR LF) after each 40-byte row, if present
    for eol in (b'\r\n', b'\n'):
        rows = raw.split(eol)
        if rows and rows[-1] == b'':
            rows = rows[:-1]
        if rows and all(len(r) == COLS for r in rows):
            return list(b''.join(rows))
    return list(raw)

def read_listing(path):
    data = []
    addr = re.compile(r'^\s*\$?[0-9A-Fa-f]{4}\s*[:\-]?\s+')
    for line in open(path):
        line = line.split(';')[0].rstrip('\n')
        if not line.strip():
            continue
        m = addr.match(line)
        if m and len(line.split()) > 1:
            line = line[m.end():]
        for tok in line.split():
            if re.fullmatch(r'[0-9A-Fa-f]{2}', tok):
                data.append(int(tok, 16))
            else:
                break          # the rest of the line is an ASCII column
    return data

def convert(data, first_row):
    if len(data) < (first_row + ROWS) * COLS:
        sys.exit(f"screen2tgl: need {(first_row + ROWS) * COLS} bytes from "
                 f"row {first_row}, found {len(data)}")
    cells, colours, warnings = [], [], 0
    for r in range(first_row, first_row + ROWS):
        row = data[r * COLS:(r + 1) * COLS]
        colour = 7
        for b in row:
            if 0x11 <= (b & 0x7F) <= 0x17:
                colour = (b & 0x7F) - 0x10
                break
        out = []
        for b in row[1:]:
            v = b & 0x7F
            if v < 0x20:
                out.append(0x20)            # control code: blank
            elif 0x40 <= v <= 0x5F:
                out.append(0x20)            # blast-through letter
                warnings += 1
            else:
                out.append(v)               # sixel cell
        cells.append(out)
        colours.append(colour)
    if warnings:
        print(f"screen2tgl: {warnings} blast-through letter cell(s) "
              f"($40-$5F) made blank", file=sys.stderr)
    return cells, colours

def write_asm(cells, colours, label, src, out):
    names = {1: 'red', 2: 'green', 3: 'yellow', 4: 'blue', 5: 'magenta',
             6: 'cyan', 7: 'white'}
    w = out.write
    w(f"; {label} - generated by tools/screen2tgl.py from {src}\n")
    w(";   24 rows x 39 cells (columns 1-39, the library's buffer layout),\n")
    w(f";   then each row's graphics colour ({label}_COL, 1-7)\n")
    w(f"{label}\n")
    for r, row in enumerate(cells):
        for half, part in enumerate((row[:20], row[20:])):
            prefix = "                FCB     "
            comment = f"     ; row {r}" if half == 0 else ""
            w(prefix + ",".join(f"${v:02X}" for v in part) + comment + "\n")
    w(f"{label}_COL\n")
    for r in range(0, ROWS, 8):
        w("                FCB     " + ",".join(str(c) for c in colours[r:r + 8])
          + f"     ; rows {r}-{r + 7}\n")
    used = sorted(set(colours))
    w(f"; colours used: {', '.join(names[c] for c in used)}\n")

def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[1],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('listing')
    ap.add_argument('-o', '--output', default='-')
    ap.add_argument('--label', default='SCREEN')
    ap.add_argument('--first-row', type=int, default=0)
    a = ap.parse_args()
    cells, colours = convert(read_screen(a.listing), a.first_row)
    out = sys.stdout if a.output == '-' else open(a.output, 'w')
    write_asm(cells, colours, a.label, a.listing, out)

if __name__ == '__main__':
    main()
