"""Generate demo/ship_model.asm from a ship definition.

Edit SHIP below to design a different ship, then run:
    python3 tools/gen_ship_model.py

Rules the model must follow (the script checks them):
  - The hull must be CONVEX: hidden-line removal draws an edge when either
    face it borders is turned towards the viewer, which is only correct
    for convex shapes.
  - Every corner must be within RADIUS_MAX of the origin, so the rotated
    depth fits the projection tables and the ship fits on screen.
  - At most 32 corners and 16 faces.

Coordinates: x to the right, y DOWN (screen y grows downwards), z away
from the viewer. Units are the same as the cube demo's.

Faces are listed as loops of corner numbers, in either direction. The
script works out each face's outward normal (the direction it faces),
which the demo rotates each frame to decide whether the face is visible.
Decals are extra lines drawn on a face (engine outlines, windows); they
are only drawn when their face is visible. Decal corners should lie on
the face's plane (near enough is fine).
"""
import math

RADIUS_MAX = 41.0
MAX_VERTS, MAX_FACES = 32, 16

SHIP = {
    "name": "KESTREL",
    "verts": [
        (0, 0, 40),                                    # 0  nose
        (14, 0, 8), (7, -9, 8), (-7, -9, 8),           # 1-3  mid ring (top half)
        (-14, 0, 8), (-7, 9, 8), (7, 9, 8),            # 4-6  mid ring (bottom half)
        (24, 0, -30), (12, -14, -30), (-12, -14, -30), # 7-9  stern ring (top half)
        (-24, 0, -30), (-12, 14, -30), (12, 14, -30),  # 10-12 stern ring (bottom half)
        (5, -4, -30), (15, -4, -30), (15, 4, -30), (5, 4, -30),        # 13-16 right engine
        (-5, -4, -30), (-15, -4, -30), (-15, 4, -30), (-5, 4, -30),    # 17-20 left engine
        (3, -4, 26), (6, -7, 14), (-6, -7, 14), (-3, -4, 26),          # 21-24 cockpit window
    ],
    "faces": [
        [0, 1, 2], [0, 2, 3], [0, 3, 4], [0, 4, 5], [0, 5, 6], [0, 6, 1],  # nose
        [1, 7, 8, 2], [2, 8, 9, 3], [3, 9, 10, 4],                          # flanks
        [4, 10, 11, 5], [5, 11, 12, 6], [6, 12, 7, 1],
        [7, 8, 9, 10, 11, 12],                                              # stern
    ],
    # (corner loop, face index): drawn as a closed outline on that face
    "decals": [
        ([13, 14, 15, 16], 12),     # right engine on the stern
        ([17, 18, 19, 20], 12),     # left engine on the stern
        ([21, 22, 23, 24], 1),      # cockpit window on the upper nose face
    ],
}

def sub(a, b): return tuple(x - y for x, y in zip(a, b))
def cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
def dot(a, b): return sum(x * y for x, y in zip(a, b))

def build(ship):
    V, F = ship["verts"], [list(f) for f in ship["faces"]]
    assert len(V) <= MAX_VERTS and len(F) <= MAX_FACES, "too many corners or faces"
    for i, v in enumerate(V):
        r = math.sqrt(dot(v, v))
        assert r <= RADIUS_MAX, f"corner {i} is {r:.1f} from the origin (max {RADIUS_MAX})"
    hull = sorted({i for f in F for i in f})
    centre = tuple(sum(V[i][k] for i in hull) / len(hull) for k in range(3))
    for fi, f in enumerate(F):
        n = cross(sub(V[f[1]], V[f[0]]), sub(V[f[2]], V[f[0]]))
        fc = tuple(sum(V[i][k] for i in f) / len(f) for k in range(3))
        if dot(n, sub(fc, centre)) < 0:                # make the normal point outward
            f.reverse()
            n = cross(sub(V[f[1]], V[f[0]]), sub(V[f[2]], V[f[0]]))
        for i in hull:                                 # convexity / planarity check
            d = dot(n, sub(V[i], V[f[0]])) / math.sqrt(dot(n, n))
            assert d <= 0.75, f"corner {i} is outside face {fi}: hull not convex (or face not flat)"
    edges, seen = [], {}
    for fi, f in enumerate(F):
        for k in range(len(f)):
            a, b = f[k], f[(k + 1) % len(f)]
            key = (min(a, b), max(a, b))
            seen.setdefault(key, []).append(fi)
    for (a, b), fs in seen.items():
        assert len(fs) == 2, f"edge {a}-{b} borders {len(fs)} faces (hull not closed)"
        edges.append((a, b, fs[0], fs[1]))
    for loop, fi in ship["decals"]:
        for k in range(len(loop)):
            edges.append((loop[k], loop[(k + 1) % len(loop)], fi, fi))
    normals = []
    for f in F:
        n = cross(sub(V[f[1]], V[f[0]]), sub(V[f[2]], V[f[0]]))
        L = math.sqrt(dot(n, n))
        normals.append(tuple(round(127 * c / L) for c in n))
    return V, F, edges, normals

def emit(ship, V, F, E, N, path):
    out = [f"; Ship model: {ship['name']} - generated by tools/gen_ship_model.py, do not edit",
           ";",
           "; SHIP_NV / SHIP_V : corners, 3 signed bytes each: x, y, z",
           "; SHIP_NF / SHIP_F : faces, 5 bytes each: C (16 bits), then the face's",
           ";                    outward normal nx, ny, nz (length 127 = 1.0).",
           ";                    C = n . P for a corner P on the face, precomputed",
           ";                    so the demo's visibility test is just",
           ";                    C - n . eye < 0, with the eye in ship coordinates.",
           "; SHIP_NE / SHIP_E : edges, 4 bytes each: corner, corner, face, face.",
           ";                    Drawn if either face is visible. Decal lines name",
           ";                    the same face twice.",
           "",
           f"SHIP_NV         FCB     {len(V)}",
           "SHIP_V"]
    for i, (x, y, z) in enumerate(V):
        out.append(f"                FCB     {x},{y},{z}".ljust(40) + f"; {i}")
    out += ["", f"SHIP_NF         FCB     {len(F)}", "SHIP_F"]
    for i, (f, n) in enumerate(zip(F, N)):
        c = dot(n, V[f[0]])
        out.append(f"                FDB     {c}".ljust(40) + f"; face {i}: C")
        out.append(f"                FCB     {n[0]},{n[1]},{n[2]}".ljust(40) + ";         normal")
    out += ["", f"SHIP_NE         FCB     {len(E)}", "SHIP_E"]
    for a, b, fa, fb in E:
        note = f"decal on face {fa}" if fa == fb else f"faces {fa},{fb}"
        out.append(f"                FCB     {a},{b},{fa},{fb}".ljust(40) + f"; {note}")
    open(path, "w").write("\n".join(out) + "\n")

if __name__ == "__main__":
    V, F, E, N = build(SHIP)
    emit(SHIP, V, F, E, N, "demo/ship_model.asm")
    print(f"{SHIP['name']}: {len(V)} corners, {len(F)} faces, {len(E)} edges -> demo/ship_model.asm")
