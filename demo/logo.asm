; ===========================================================================
; Splash-screen demo: an existing teletext screen, turned over with
; TGL_FLIPH
;
;   Shows a teletext graphics screen converted by tools/screen2tgl.py, then
;   turns it over every couple of seconds: it narrows to the centre line
;   and opens out again mirror-reversed, like a card. Press any key to exit.
;
;   The picture is in logo_screen.asm, in the library's buffer layout: 24
;   rows of 39 cells (columns 1-39) then the 24 row colours. To use your
;   own screen, regenerate it from a hex listing of the screen memory:
;
;       python3 tools/screen2tgl.py listing.txt --label LOGO \
;               -o demo/logo_screen.asm
;
;   (add --first-row 1 if graphics row 0 is screen row 1, and so on).
;   The library draws contiguous graphics, so a separated-graphics screen
;   shows as solid blocks.
;
;   Loading: tgl.bin at $1000 (TGL_BASE below), logo.bin at $2800.
;   Run from START ($2800). Works with either machine's library build.
; ===========================================================================

TGL_BASE        EQU     $1000
                INCLUDE "tgl_api.inc"

BUFFER          EQU     $3800           ; off-screen buffer (960 bytes)
STACK_TOP       EQU     $0200           ; stack $0100-$01FF

FLIP_TICKS      EQU     2               ; flip speed: 50Hz ticks per frame
                                        ;  (2 = about 0.7 s, 3 = about 1 s)
PAUSE           EQU     100             ; pause between flips, in 50Hz ticks

WAITN           EQU     $80             ; pause counter
ROW             EQU     $81             ; row being copied

                ORG     $2800

START           LDS     #STACK_TOP
                CLRA                    ; DP = $00 for the library
                TFR     A,DP
                SETDP   $00
                ANDCC   #$EF            ; IRQs on (keyboard)
                JSR     TGL_INIT
                LDX     #BUFFER
                JSR     TGL_SETBUF
                JSR     TGL_CLS
                CLRA                    ; status row title
                LDX     #TITLE
                JSR     TGL_TEXT

; ---------------------------------------------------------------------------
; Copy the picture into the buffer: for each row, its 39 cells into
; columns 1-39, then its colour with TGL_COLOUR (which writes column 0 and
; remembers it, so TGL_CLS would keep it)
; ---------------------------------------------------------------------------
                LDY     #LOGO           ; Y -> the picture's cells
                LDU     #BUFFER+1       ; U -> column 1 of buffer row 0
                CLR     <ROW
COPYROW         LDB     #39             ; 39 cells
COPYCELL        LDA     ,Y+
                STA     ,U+
                DECB
                BNE     COPYCELL
                LEAU    1,U             ; skip column 0 of the next row
                LDX     #LOGO_COL       ; this row's colour (1-7)
                LDB     <ROW
                ABX
                LDB     ,X
                CLRA
                TFR     D,X             ; X = colour
                LDA     <ROW            ; A = B = this row
                LDB     <ROW
                JSR     TGL_COLOUR
                INC     <ROW
                LDA     <ROW
                CMPA    #24
                BLO     COPYROW
                JSR     TGL_BLIT

; ---------------------------------------------------------------------------
; Pause, flip, repeat (any key exits)
; ---------------------------------------------------------------------------
LOOP            LDA     #PAUSE          ; pause, checking for a key
                STA     <WAITN
WAIT            JSR     TGL_INKEY
                LBNE    TGL_EXIT
                LDA     #1              ; one 50Hz tick
                JSR     TGL_PACE
                DEC     <WAITN
                BNE     WAIT
                LDA     #FLIP_TICKS     ; turn the picture over
                JSR     TGL_FLIPH
                BRA     LOOP

; Status row title. $86 cyan, $83 yellow text codes.
TITLE           FCB     $86
                FCC     "SPLASH SCREEN"
                FCB     $83
                FCC     "ANY KEY EXITS"
                FCB     0

; The picture (generated by tools/screen2tgl.py)
                INCLUDE "logo_screen.asm"
